"""Shared building blocks for analysis methods.

A method turns a structured objective (params) and a strategy into one or more
*stages*. Each stage is a self-contained Python script that runs in the
sandbox and writes computed tables, charts, metrics and verifiable claims.

Parameters are injected as a JSON string literal, never by string
concatenation into code, so column names cannot inject code.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

import pandas as pd

TASK_TYPES = [
    "descriptive", "comparison", "hypothesis_test", "classification", "regression",
    "forecasting", "segmentation", "anomaly_detection", "profit_change",
]


@dataclass
class Stage:
    key: str
    title: str
    code: str
    rationale: str = ""
    kind: str = "python"  # python | sql (sql stages still run through the sandbox via sqlite3)


@dataclass
class Assessment:
    status: str  # succeeded | weak | failed | invalid
    diagnosis: str | None = None
    reason_code: str | None = None  # machine-readable: e.g. class_imbalance, non_normal, overfit, not_better_than_baseline
    headline_metric: tuple[str, float] | None = None


@dataclass
class Finding:
    title: str
    detail: str
    evidence: list[str] = field(default_factory=list)  # claim ids or metric names
    kind: str = "observation"  # observation | inference | caution
    confidence: str = "medium"

    def to_dict(self) -> dict[str, Any]:
        return self.__dict__.copy()


@dataclass
class Recommendation:
    action: str
    rationale: str
    evidence: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        return {**self.__dict__, "kind": "suggestion"}


def header(params: dict[str, Any], strategy: str, imports: str) -> str:
    payload = json.dumps({**params, "strategy": strategy}, sort_keys=True, default=str)
    return (
        "# Generated by InsightForge AI. Runs inside the sandbox; reproducible with `python analysis.py`\n"
        "# next to data.csv and ifrt.py.\n"
        f"{imports.strip()}\n"
        "import json\n"
        "import ifrt\n\n"
        f"P = json.loads({payload!r})\n"
        "SEED = 42\n"
    )


def sql_ident(name: str) -> str:
    """Quote an SQL identifier for SQLite (double quotes, internal quotes doubled)."""
    return '"' + str(name).replace('"', '""') + '"'


class Method:
    key: str = ""
    task_type: str = ""
    title: str = ""
    strategies: list[str] = []
    retry_map: dict[str, list[str]] = {}

    def requirements(self, profile: dict[str, Any], params: dict[str, Any]) -> list[str]:
        return []

    def stages(self, params: dict[str, Any], strategy: str) -> list[Stage]:
        raise NotImplementedError

    def assess(self, result: dict[str, Any], params: dict[str, Any], strategy: str) -> Assessment:
        return Assessment("succeeded")

    def conditions(self, df: pd.DataFrame, profile: dict[str, Any], params: dict[str, Any]) -> dict[str, str]:
        return {}

    def findings(self, result: dict[str, Any], params: dict[str, Any]) -> tuple[list[Finding], list[Recommendation], list[str]]:
        """Returns findings, recommendations, limitations — all derived from `result`."""
        return [], [], []

    def next_strategy(self, tried: list[str], reason_code: str | None, ranked: list[str]) -> str | None:
        for s in self.retry_map.get(reason_code or "", []):
            if s not in tried and s in self.strategies:
                return s
        for s in ranked:
            if s not in tried:
                return s
        return None


def fmt_num(x: float | None, money: bool = False) -> str:
    if x is None:
        return "n/a"
    sign = "-" if x < 0 else ""
    ax = abs(x)
    if ax >= 1e6:
        s = f"{ax / 1e6:.2f}M"
    elif ax >= 1e4:
        s = f"{ax / 1e3:.1f}k"
    elif ax >= 100:
        s = f"{ax:,.0f}"
    else:
        s = f"{ax:,.2f}"
    return f"{sign}{'$' if money else ''}{s}"


def fmt_p(p: float | None) -> str:
    if p is None:
        return "n/a"
    return "p < 0.001" if p < 0.001 else f"p = {p:.3f}"


def metric_value(result: dict[str, Any], name: str, default=None):
    m = result.get("metrics", {}).get(name)
    return m.get("value", default) if isinstance(m, dict) else default
